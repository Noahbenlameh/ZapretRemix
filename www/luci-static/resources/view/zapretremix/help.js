function section(title, body) {
	return E('div', { 'style': 'margin-bottom:28px;' }, [
		E('h3', {}, title),
		body
	]);
}

function p(text) {
	return E('p', { 'style': 'line-height:1.6;margin:6px 0;' }, text);
}

// A numbered step in a horizontal flow — the "с чего начать" walkthrough.
function step(n, title, text) {
	return E('div', { 'style': 'flex:1;min-width:180px;background:rgba(120,140,160,0.08);border-radius:6px;padding:14px;' }, [
		E('div', { 'style': 'display:flex;align-items:center;gap:8px;margin-bottom:6px;' }, [
			E('span', { 'style': 'display:inline-flex;align-items:center;justify-content:center;width:24px;height:24px;border-radius:50%;background:#3a7;color:#fff;font-weight:bold;font-size:13px;flex-shrink:0;' }, String(n)),
			E('strong', {}, title)
		]),
		E('div', { 'style': 'font-size:12.5px;line-height:1.5;color:inherit;opacity:0.85;' }, text)
	]);
}

// A card in the "все вкладки" overview grid.
function tabCard(icon, name, text) {
	return E('div', { 'style': 'background:rgba(120,140,160,0.06);border-radius:6px;padding:12px 14px;' }, [
		E('div', { 'style': 'font-size:20px;margin-bottom:4px;' }, icon),
		E('div', { 'style': 'font-weight:bold;margin-bottom:4px;' }, name),
		E('div', { 'style': 'font-size:12px;line-height:1.5;opacity:0.85;' }, text)
	]);
}

// Color-coded callout — 'ok' (green), 'warn' (amber), 'danger' (red), 'info' (neutral blue-gray).
function callout(kind, title, text) {
	var colors = {
		ok:     { border: '#3a7', bg: 'rgba(60,170,100,0.08)' },
		warn:   { border: '#c90', bg: 'rgba(200,150,0,0.08)' },
		danger: { border: '#c33', bg: 'rgba(200,50,50,0.08)' },
		info:   { border: '#369', bg: 'rgba(50,100,150,0.08)' }
	};
	var c = colors[kind] || colors.info;
	return E('div', { 'style': 'border-left:4px solid ' + c.border + ';background:' + c.bg + ';border-radius:0 6px 6px 0;padding:10px 14px;margin:8px 0;' }, [
		title ? E('div', { 'style': 'font-weight:bold;margin-bottom:4px;' }, title) : '',
		E('div', { 'style': 'font-size:13px;line-height:1.55;' }, text)
	]);
}

